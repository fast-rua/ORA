const TABLES: Record<Lang, Record<Key, string>> = { en: EN, zh: ZH };

function stored(): Lang | null {
  try {
    const value = globalThis.localStorage?.getItem(STORE_KEY);
    return value === "zh" || value === "en" ? value : null;
  } catch {
    return null;
  }
}

/** The browser's language: Chinese for a `zh*` language, else English. */
export function browserLang(languages: readonly string[] = globalThis.navigator?.languages ?? [globalThis.navigator?.language ?? ""]): Lang {
  const first = languages.find((item) => typeof item === "string" && item) ?? "";
  return /^zh/i.test(first) ? "zh" : "en";
}

let current: Lang = stored() ?? browserLang();
const listeners = new Set<() => void>();

export function lang(): Lang {
  return current;
}

export function setLang(next: Lang, remember = true): void {
  if (next === current) return;
  current = next;
  if (remember) {
    try {
      globalThis.localStorage?.setItem(STORE_KEY, next);
    } catch {
      // a browser that keeps nothing: the choice lasts this page
    }
  }
  if (typeof document !== "undefined") document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
  for (const listener of listeners) listener();
}

/** The current language; the component re-renders when it changes. */
export function useLang(): Lang {
  return useSyncExternalStore((listener) => {
    listeners.add(listener);
    return () => listeners.delete(listener);
  }, () => current, () => current);
}

export function t(key: Key, params: Record<string, string | number | null | undefined> = {}): string {
  const text = TABLES[current][key] ?? EN[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (params[name] === undefined || params[name] === null
    ? match : String(params[name])));
}

/** Seconds as the live status counts them: 4 s, 1 min 05 s. */
export function seconds(ms: number): string {
  const total = Math.max(0, Math.floor(ms / 1000));
  if (total < 60) return current === "zh" ? `${total} 秒` : `${total} s`;
  const rest = String(total % 60).padStart(2, "0");
  return current === "zh" ? `${Math.floor(total / 60)} 分 ${rest} 秒` : `${Math.floor(total / 60)} min ${rest} s`;
}

/** A duration for the timeline: 0.8 s, 12 s. */
export function duration(secondsValue: number | null): string {
  if (secondsValue === null || !Number.isFinite(secondsValue)) return "—";
  const text = secondsValue < 10 ? secondsValue.toFixed(1) : String(Math.round(secondsValue));
  return current === "zh" ? `${text} 秒` : `${text} s`;
}

export function hasKey(key: string): key is Key {
  return key in EN;
}
