"""``ora dev cli-reference``: the command reference, generated from ``ora``'s own parser.

    ora dev cli-reference              print the reference (Markdown)
    ora dev cli-reference --write      write it to docs/usage/cli-reference.md in this checkout
    ora dev cli-reference --check      exit 1 when docs/usage/cli-reference.md differs from the parser

Every public command, in ``ora --help``'s groups and order, with the help
argparse prints for it and for each of its subcommands, at a fixed width. A
command that hands the rest of its line to an operator tool (``ora spec``,
``ora qualify``, ``ora report`` ...) shows its own description and the tool's
``module:function``; ``ora <command> ... --help`` prints the tool's arguments.
``tests/ora/app/test_cli_reference.py`` fails when the page is out of date.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Iterator

#: The page in a source checkout.
PAGE = Path(__file__).resolve().parents[2] / "docs" / "usage" / "cli-reference.md"
#: Columns argparse wraps the help at, whatever the terminal.
WIDTH = 100
HEADER = """# ORA command reference

<!-- Generated by `ora dev cli-reference --write` from ora's parser; do not edit by hand. -->

This page is `ora --help` and every command's `--help`, generated from the
parser (`ora/app/main.py` and one module per command group in `ora/app/`). The
[command guide](commands.md) explains what each command writes and
when to use it. A command that hands the rest of its line to an operator tool
lists the tool here; `ora COMMAND ... --help` prints the tool's own arguments.
"""


def _subcommands(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in parser._actions:  # noqa: SLF001 - argparse keeps no public accessor
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            return dict(action.choices)
    return {}


def _block(text: str) -> list[str]:
    return ["```text", text.rstrip("\n"), "```", ""]


#: Tool leaves that run what each backend declares: the registry field they read.
BACKEND_TOOLS = {"ora spec": "spec_tools", "ora qualify": "qualify_tools"}


def _backend_tools(field: str) -> Iterator[str]:
    from ora.orchestrator.backends import registry

    yield "| Environment | Tool | What it does | Runs |"
    yield "|---|---|---|---|"
    for item in registry.backends():
        aliases = [alias for alias, kind in registry.ALIASES.items() if kind == item.kind]
        for name, tool in getattr(item, field).items():
            runs = " ".join([tool.target, *tool.arguments])
            yield f"| {', '.join([item.kind, *aliases])} | `{name}` | {tool.help} | `{runs}` |"
    yield ""


def _sections(parser: argparse.ArgumentParser, depth: int) -> Iterator[str]:
    tool = getattr(parser, "tool", None)
    yield f"{'#' * depth} `{parser.prog}`"
    yield ""
    if tool is not None:
        yield from _block(parser.description or "")
        yield f"Runs `{tool}` on the rest of the line."
        yield ""
        if parser.prog in BACKEND_TOOLS:
            yield from _backend_tools(BACKEND_TOOLS[parser.prog])
        return
    yield from _block(parser.format_help())
    for child in _subcommands(parser).values():
        yield from _sections(child, min(depth + 1, 6))


def render() -> str:
    """The whole page, the same on every host and terminal."""

    from .main import GROUPS, PUBLIC_COMMANDS, build_parser, overview

    saved = os.environ.get("COLUMNS")
    os.environ["COLUMNS"] = str(WIDTH + 2)  # argparse wraps at the terminal width less two
    try:
        commands = _subcommands(build_parser())
        lines = [HEADER, "## `ora --help`", "", *_block(overview("en"))]
        for (title, _), entries in GROUPS:
            lines += [f"## {title}", ""]
            for name, *_ in entries:
                if name in PUBLIC_COMMANDS:
                    lines += _sections(commands[name], 3)
    finally:
        if saved is None:
            os.environ.pop("COLUMNS", None)
        else:
            os.environ["COLUMNS"] = saved
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--write", action="store_true", help=f"write {PAGE.name} in docs/usage of this checkout")
    action.add_argument("--check", action="store_true", help="exit 1 when the page differs from the parser")
    args = parser.parse_args(argv)
    page = render()
    if not (args.write or args.check):
        sys.stdout.write(page)
        return 0
    if not PAGE.parent.is_dir():
        print(f"ora dev cli-reference: {PAGE.parent} is not here; it exists only in a source checkout",
              file=sys.stderr)
        return 2
    if args.write:
        PAGE.write_text(page, encoding="utf-8")
        print(PAGE)
        return 0
    if PAGE.is_file() and PAGE.read_text(encoding="utf-8") == page:
        return 0
    print(f"ora dev cli-reference: {PAGE} is out of date; run ./scripts/ora dev cli-reference --write",
          file=sys.stderr)
    return 1


__all__ = ["PAGE", "WIDTH", "main", "render"]
